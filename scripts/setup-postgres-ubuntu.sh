#!/usr/bin/env bash
# One-shot PostgreSQL 16 setup for 2C/2G Tencent Lighthouse + Baota.
# Creates slime_prod / slime_dev, low-memory tuning, and user_game_infos table.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
SCHEMA_SQL="${PROJECT_DIR}/sql/001_init_schema.sql"
CREDENTIALS_FILE="/root/slime-postgres-credentials.txt"
BACKUP_DIR="/www/backup/postgres"

if [[ "${EUID}" -ne 0 ]]; then
  echo "[ERROR] Please run with sudo: sudo bash scripts/setup-postgres-ubuntu.sh"
  exit 1
fi

if [[ ! -f "${SCHEMA_SQL}" ]]; then
  echo "[ERROR] Schema file not found: ${SCHEMA_SQL}"
  exit 1
fi

echo "[1/6] Installing PostgreSQL 16..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
if ! command -v psql >/dev/null 2>&1; then
  apt-get install -y postgresql postgresql-contrib
fi

PG_VERSION="$(ls /etc/postgresql 2>/dev/null | sort -V | tail -n 1 || true)"
if [[ -z "${PG_VERSION}" ]]; then
  echo "[ERROR] PostgreSQL installed but /etc/postgresql not found"
  exit 1
fi

PG_CONF="/etc/postgresql/${PG_VERSION}/main/postgresql.conf"
PG_HBA="/etc/postgresql/${PG_VERSION}/main/pg_hba.conf"
echo "[INFO] Detected PostgreSQL ${PG_VERSION}"

echo "[2/6] Applying low-memory tuning for 2C/2G..."
# Keep listen address local-only for security.
sed -i "s/^#\?listen_addresses.*/listen_addresses = '127.0.0.1'/" "${PG_CONF}"
sed -i "s/^#\?max_connections.*/max_connections = 30/" "${PG_CONF}"
sed -i "s/^#\?shared_buffers.*/shared_buffers = 64MB/" "${PG_CONF}"
sed -i "s/^#\?work_mem.*/work_mem = 4MB/" "${PG_CONF}"
sed -i "s/^#\?maintenance_work_mem.*/maintenance_work_mem = 64MB/" "${PG_CONF}"
sed -i "s/^#\?effective_cache_size.*/effective_cache_size = 512MB/" "${PG_CONF}"
sed -i "s/^#\?wal_buffers.*/wal_buffers = 4MB/" "${PG_CONF}"
sed -i "s/^#\?checkpoint_completion_target.*/checkpoint_completion_target = 0.9/" "${PG_CONF}"
sed -i "s/^#\?random_page_cost.*/random_page_cost = 1.1/" "${PG_CONF}"

# Ensure local password auth for app roles
if ! grep -q "slime_prod_user\|slime_dev_user" "${PG_HBA}"; then
  cat >> "${PG_HBA}" <<'EOF'

# Slime Express app roles (local only)
local   slime_prod   slime_prod_user                     scram-sha-256
host    slime_prod   slime_prod_user   127.0.0.1/32       scram-sha-256
local   slime_dev    slime_dev_user                      scram-sha-256
host    slime_dev    slime_dev_user    127.0.0.1/32       scram-sha-256
EOF
fi

systemctl enable postgresql
systemctl restart postgresql
sleep 2

gen_password() {
  openssl rand -base64 24 | tr -d '=+/\"'\''`' | cut -c1-24
}

PROD_PASS="$(gen_password)"
DEV_PASS="$(gen_password)"

echo "[3/6] Creating databases and roles..."
sudo -u postgres psql <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'slime_prod_user') THEN
    CREATE ROLE slime_prod_user LOGIN PASSWORD '${PROD_PASS}';
  ELSE
    ALTER ROLE slime_prod_user WITH LOGIN PASSWORD '${PROD_PASS}';
  END IF;

  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'slime_dev_user') THEN
    CREATE ROLE slime_dev_user LOGIN PASSWORD '${DEV_PASS}';
  ELSE
    ALTER ROLE slime_dev_user WITH LOGIN PASSWORD '${DEV_PASS}';
  END IF;
END
\$\$;

SELECT 'CREATE DATABASE slime_prod OWNER slime_prod_user'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'slime_prod')\gexec

SELECT 'CREATE DATABASE slime_dev OWNER slime_dev_user'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'slime_dev')\gexec

GRANT ALL PRIVILEGES ON DATABASE slime_prod TO slime_prod_user;
GRANT ALL PRIVILEGES ON DATABASE slime_dev TO slime_dev_user;
SQL

echo "[4/6] Applying schema to slime_prod and slime_dev..."
sudo -u postgres psql -d slime_prod -f "${SCHEMA_SQL}"
sudo -u postgres psql -d slime_dev -f "${SCHEMA_SQL}"

sudo -u postgres psql -d slime_prod <<'SQL'
ALTER TABLE user_game_infos OWNER TO slime_prod_user;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO slime_prod_user;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO slime_prod_user;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO slime_prod_user;
SQL

sudo -u postgres psql -d slime_dev <<'SQL'
ALTER TABLE user_game_infos OWNER TO slime_dev_user;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO slime_dev_user;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO slime_dev_user;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO slime_dev_user;
SQL

echo "[5/6] Preparing backup directory..."
mkdir -p "${BACKUP_DIR}"
chmod 750 "${BACKUP_DIR}"

echo "[6/6] Writing credentials backup to ${CREDENTIALS_FILE}"
umask 077
cat > "${CREDENTIALS_FILE}" <<EOF
# Generated by setup-postgres-ubuntu.sh at $(date -Iseconds)
# Keep this file private. Copy the lines below into each .env

正式服连接串: DATABASE_URL=postgresql://slime_prod_user:${PROD_PASS}@127.0.0.1:5432/slime_prod
测试服连接串: DATABASE_URL=postgresql://slime_dev_user:${DEV_PASS}@127.0.0.1:5432/slime_dev

# Local Windows tunnel tip:
# After start-dev-db-tunnel.bat, use port 15432:
# DATABASE_URL=postgresql://slime_dev_user:${DEV_PASS}@127.0.0.1:15432/slime_dev
EOF
chmod 600 "${CREDENTIALS_FILE}"

echo
echo "=============================================="
echo " PostgreSQL setup completed successfully"
echo "=============================================="
echo "正式服连接串: DATABASE_URL=postgresql://slime_prod_user:${PROD_PASS}@127.0.0.1:5432/slime_prod"
echo "测试服连接串: DATABASE_URL=postgresql://slime_dev_user:${DEV_PASS}@127.0.0.1:5432/slime_dev"
echo
echo "Credentials also saved to: ${CREDENTIALS_FILE}"
echo "Copy these two lines into a local notepad before continuing."
echo "=============================================="
